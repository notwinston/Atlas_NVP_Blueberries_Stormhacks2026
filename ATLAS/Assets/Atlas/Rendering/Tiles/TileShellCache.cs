// P1-B06: the three shared tile shells (Near n = 16, Mid n = 8, Far n = 4; MP 3.4, 8.4), rebuilt in place when L changes.
using System;
using UnityEngine;

namespace Atlas.Rendering
{
    public sealed class TileShellCache : IDisposable
    {
        readonly TileMeshGenerator gen = new TileMeshGenerator(TilePalette.Default);
        Mesh near, mid, far;

        public TileShellCache(int q, double lengthScale)
        {
            Q = q;
            near = new Mesh { name = "TileShellNear", hideFlags = HideFlags.DontSave };
            mid = new Mesh { name = "TileShellMid", hideFlags = HideFlags.DontSave };
            far = new Mesh { name = "TileShellFar", hideFlags = HideFlags.DontSave };
            Rebuild(lengthScale);
        }

        public double L { get; private set; }
        public int Q { get; }

        public Mesh Get(TileLod lod) => lod == TileLod.Near ? near : lod == TileLod.Mid ? mid : far;

        /// <summary>The same Mesh objects, regenerated by B05's Build(spec, mesh) [P1-B06 D6: KerbMask 0, PostMask 0xF].</summary>
        public void Rebuild(double lengthScale)
        {
            gen.Build(TileMeshSpec.Hyperbolic(Q, lengthScale, TileLod.Near, 0, 0xF), near);
            gen.Build(TileMeshSpec.Hyperbolic(Q, lengthScale, TileLod.Mid, 0, 0xF), mid);
            gen.Build(TileMeshSpec.Hyperbolic(Q, lengthScale, TileLod.Far, 0, 0xF), far);
            L = lengthScale;
        }

        public void Dispose()
        {
            Kill(near); Kill(mid); Kill(far);
            near = mid = far = null;
        }

        static void Kill(UnityEngine.Object o)
        {
            if (o == null) return;
            if (Application.isPlaying) UnityEngine.Object.Destroy(o); else UnityEngine.Object.DestroyImmediate(o);
        }
    }
}
