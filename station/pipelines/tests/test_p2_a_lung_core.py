# P2-A24: per-frame vertex step of the real chest. REPORT ONLY: the acceptance (<= 1 mm at display
# scale, no visible jump at the wrap) needs the Editor.
# =============================================================================================
def test_p2_a24_chest_vertex_step_report(lung_core, lung101_case, tmp_path):
    from atlas_pipelines import glb

    chest = lung101_case / "chest.glb"
    if not chest.is_file():
        pytest.skip("chest vertex step NOT REPORTED: the lung101 package has no chest.glb")
    meshes = glb.read_glb(chest)
    names = [f"phase_{k}" for k in range(10)]
    targets = np.concatenate([np.stack([m.targets[n] for n in names]) for m in meshes], axis=1).astype("<f4")   # [10, V, 3]
    n_vert = targets.shape[1]
    dump = tmp_path / "chest_targets.bin"
    dump.write_bytes(struct.pack("<ii", 10, n_vert) + targets.tobytes())

    proc = lung_core("chest", dump, FPS, BREATH_S)
    assert proc.returncode == 0, proc.stderr
    m = _measures(proc.stdout)

    # independent numpy value of the same quantity
    def weights(phase: float) -> np.ndarray:
        p = phase % 10.0
        k = int(np.floor(p))
        w = np.zeros(10)
        w[k] = 1.0 - (p - k)
        w[(k + 1) % 10] += p - k
        return w

    frames = int(round(FPS * BREATH_S))
    worst, at_wrap = 0.0, 0.0
    t64 = targets.astype(np.float64)
    for f in range(frames):
        p0, p1 = 10.0 * f / frames, (10.0 * (f + 1) / frames) % 10.0
        d = np.tensordot(weights(p1) - weights(p0), t64, axes=1)
        step = float(np.sqrt((d * d).sum(axis=1)).max())
        worst = max(worst, step)
        if p0 >= 9.0 or p1 < p0:
            at_wrap = max(at_wrap, step)
    assert m["chest_vertices"] == n_vert
    assert m["chest_max_step_per_frame_m"] == pytest.approx(worst, abs=1e-6)
    assert m["chest_max_step_across_wrap_m"] == pytest.approx(at_wrap, abs=1e-6)
    print(f"\n--- P2-A24 chest.glb of lung101 ({n_vert} vertices, 4 meshes), {FPS:g} fps, {BREATH_S:g} s breath, linear blend:"
          f"\n    largest vertex step per frame = {1000 * worst:.3f} mm at display scale (M = 15) = {1000 * worst / 15:.4f} mm patient"
          f"\n    largest step on the frames of the wrap 9 -> 0 = {1000 * at_wrap:.3f} mm at display scale"
          f"\n    (plan: <= 1 mm at display scale, to be judged in the Editor; not asserted here)")
