def test_core_sources_are_engine_free(pipelines_root):
    """System only: no UnityEngine, no Unity.Mathematics, no third-party namespace, no package reference."""
    root = pipelines_root / "csharp" / CORE
    sources = sorted(root.glob("*.cs"))
    assert sources
    for src in sources:
        text = src.read_text(encoding="utf-8")
        assert "Unity" not in re.sub(r"//.*", "", text), f"{src.name} mentions Unity outside comments"
        for using in re.findall(r"^\s*using\s+([A-Za-z0-9_.]+)\s*;", text, flags=re.M):
            assert using == "System" or using.startswith("System.") or using == "Atlas.Cases", f"{src.name}: using {using}"
        assert "DateTime" not in text and "Stopwatch" not in text and "Environment.Tick" not in text, f"{src.name} reads a clock"
        assert "Random" not in text, f"{src.name} is not deterministic"
    proj = (root / f"{CORE}.csproj").read_text(encoding="utf-8")
    assert "PackageReference" not in proj
    assert "<TargetFramework>netstandard2.1</TargetFramework>" in proj and "<LangVersion>9.0</LangVersion>" in proj
    assert (root / "README.md").is_file()


