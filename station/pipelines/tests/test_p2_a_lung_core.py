# P2-A29 M2: hit = rho(p) from occ.r8, against an independent Python sample at 200 seeded points
# =============================================================================================
def _python_occ_sample(case_dir: Path, pts: np.ndarray) -> np.ndarray:
    """Independent of the C# code: scipy's linear interpolation on the voxel-centre lattice of the contract
    (section 7: x fastest; voxel i centred at bbox_min + (i + 0.5) (bbox_max - bbox_min) / 64), edges clamped."""
    from scipy.ndimage import map_coordinates

    table = json.loads((case_dir / "table.json").read_text(encoding="utf-8"))
    dims = table["occ"]["dims"]
    lo = np.array(table["occ"]["bbox_min_mm"], float)
    hi = np.array(table["occ"]["bbox_max_mm"], float)
    raw = np.frombuffer((case_dir / "occ.r8").read_bytes(), dtype=np.uint8)
    assert raw.size == dims[0] * dims[1] * dims[2]
    vol = raw.reshape(dims[2], dims[1], dims[0]).astype(np.float64) / 255.0       # [iz, iy, ix]
    g = (pts - lo) / (hi - lo) * np.array(dims, float) - 0.5                       # index coordinates x, y, z
    rho = map_coordinates(vol, [g[:, 2], g[:, 1], g[:, 0]], order=1, mode="nearest")
    inside = np.all((pts >= lo) & (pts <= hi), axis=1)
    return np.where(inside, rho, 0.0)


def test_p2_a29_m2_hit_equals_occ_sample(lung_core, case_dir, tmp_path):
    table = json.loads((case_dir / "table.json").read_text(encoding="utf-8"))
    lo = np.array(table["occ"]["bbox_min_mm"], float)
    hi = np.array(table["occ"]["bbox_max_mm"], float)
    rng = np.random.default_rng(M2_SEED)
    # half uniform in the grid's box, half scattered round the argmax-rho point (so the lesion's edge is sampled)
    uniform = lo + rng.random((M2_POINTS // 2, 3)) * (hi - lo)
    spread = (hi - lo) / 6.0
    near = np.array(table["argmax_rho_mm"], float) + rng.normal(size=(M2_POINTS - M2_POINTS // 2, 3)) * spread
    pts = np.vstack([uniform, near])
    assert pts.shape == (M2_POINTS, 3)
    points_file = tmp_path / "points.txt"
    points_file.write_text("".join(f"{p[0]!r} {p[1]!r} {p[2]!r}\n" for p in pts.tolist()), encoding="ascii")

    proc = lung_core("m2", case_dir, points_file)
    assert proc.returncode == 0, proc.stderr
    got = np.array([[float(x) for x in line.split()] for line in proc.stdout.splitlines() if line.strip()])
    assert got.shape == (M2_POINTS, 2)
    want = _python_occ_sample(case_dir, pts)
    worst = float(np.max(np.abs(got[:, 0] - want)))
    print(f"\n--- M2 {case_dir.name}: worst |C# hit - Python occ.r8 sample| over {M2_POINTS} points = {worst:.3e}; "
          f"{int(np.sum(want > 0))} points with rho > 0, {int(np.sum((want > 0) & (want < table['max_rho'])))} strictly between")
    assert worst <= M2_TOL
    assert np.all(got[:, 1] == table["max_rho"])                 # best = max rho
    assert np.all((got[:, 0] >= 0.0) & (got[:, 0] <= 1.0))
    assert np.sum(want > 0) >= 40, "the seeded points must reach into the occupancy"
    raw = np.frombuffer((case_dir / "occ.r8").read_bytes(), dtype=np.uint8)
    assert abs(raw.max() / 255.0 - table["max_rho"]) <= M2_TOL


