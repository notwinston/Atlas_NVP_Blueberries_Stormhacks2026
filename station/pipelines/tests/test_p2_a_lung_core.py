def _find_dotnet() -> str | None:
    candidates = []
    on_path = shutil.which("dotnet")
    if on_path:
        candidates.append(Path(on_path))
    if os.environ.get("DOTNET_ROOT"):
        candidates.append(Path(os.environ["DOTNET_ROOT"]) / "dotnet")
    candidates.append(Path.home() / ".dotnet" / "dotnet")
    for c in candidates:
        if c.is_file() and os.access(c, os.X_OK):
            return str(c)
    return None


@pytest.fixture(scope="session")
def lung_core(pipelines_root):
    """Builds Atlas.Lung.Core.Tests once; returns run(*args) -> CompletedProcess."""
    exe = _find_dotnet()
    if exe is None:
        pytest.skip("Atlas.Lung.Core tests NOT RUN: no .NET SDK found on PATH, in $DOTNET_ROOT or in ~/.dotnet")
    env = dict(os.environ)
    env.setdefault("DOTNET_ROOT", str(Path(exe).resolve().parent))
    env["DOTNET_CLI_TELEMETRY_OPTOUT"] = "1"
    env["DOTNET_NOLOGO"] = "1"
    env["DOTNET_SYSTEM_GLOBALIZATION_INVARIANT"] = "1"     # the SDK aborts without ICU otherwise
    proj = pipelines_root / "csharp" / TESTS / f"{TESTS}.csproj"
    build = subprocess.run([exe, "build", str(proj), "-c", "Release", "-v", "quiet"], capture_output=True, text=True, env=env)
    assert build.returncode == 0, f"dotnet build {TESTS} failed:\n{build.stdout}\n{build.stderr}"
    found = sorted((pipelines_root / "csharp" / TESTS / "bin" / "Release").glob(f"*/{TESTS}.dll"))
    assert found, f"{TESTS}.dll not produced"

    def run(*args) -> subprocess.CompletedProcess:
        return subprocess.run([exe, str(found[0]), *map(str, args)], capture_output=True, text=True, env=env)

    return run


def _measures(stdout: str) -> dict[str, float]:
    out = {}
    for line in stdout.splitlines():
        m = re.match(r"MEASURE (\S+) (\S+)$", line)
        if m:
            out[m.group(1)] = float(m.group(2))
    return out


def _report(title: str, measures: dict[str, float]) -> None:
    print(f"\n--- {title}")
    for k in sorted(measures):
        print(f"    {k} = {measures[k]!r}")


