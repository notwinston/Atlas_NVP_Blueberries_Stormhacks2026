# P2-A27 gating, against an independent read of table.json
# =============================================================================================
def test_p2_a27_gating_equals_table(lung_core, case_dir):
    table = json.loads((case_dir / "table.json").read_text(encoding="utf-8"))
    gating = table["gating_cm3"]
    itv = table["itv_cm3"]
    proc = lung_core("gate", case_dir)
    assert proc.returncode == 0, proc.stderr
    rows = [line.split() for line in proc.stdout.splitlines() if line.strip()]
    assert len(rows) == 100
    seen = set()
    for row in rows:
        start, length = int(row[0]), int(row[1])
        vol, duty, best, best_start, reduction, score = float(row[2]), float(row[3]), float(row[4]), int(row[5]), float(row[6]), float(row[7])
        seen.add((start, length))
        want = gating[start][length - 1]
        assert abs(vol - want) <= GATING_TOL * want, f"arc ({start}, {length}): {vol} vs table {want}"
        assert duty == length / 10
        column = [gating[s][length - 1] for s in range(10)]
        assert best == min(column) and best_start == column.index(min(column))
        assert reduction == pytest.approx(1.0 - want / itv, abs=1e-12)
        best_red = itv - best
        want_score = 1.0 if best_red <= 0 else min(1.0, max(0.0, (itv - want) / best_red))
        assert score == pytest.approx(want_score, abs=1e-12)
    assert seen == {(s, l) for s in range(10) for l in range(1, 11)}


