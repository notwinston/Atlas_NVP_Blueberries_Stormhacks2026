def _source_dir(case_id: str) -> Path | None:
    env = os.environ.get("ATLAS_CASES_DIR")
    if env:
        d = Path(env) / case_id
        assert d.is_dir(), f"ATLAS_CASES_DIR is set but {d} does not exist"
        return d
    d = paths.default_out_dir() / "cases" / case_id       # not created here
    if all((d / f).is_file() for f in CASE_FILES):
        return d
    return None


def _copy_case(src: Path, dst: Path) -> Path:
    dst.mkdir(parents=True, exist_ok=True)
    for name in CASE_FILES + ["chest.glb"]:
        if (src / name).is_file():
            shutil.copyfile(src / name, dst / name)
    missing = [f for f in CASE_FILES if not (dst / f).is_file()]
    assert not missing, f"{src}: missing {missing}"
    return dst


